            candidate_prompt = find_imageid_in_json(candidate_json_path, image_id, "top_10_preds")
            if not candidate_prompt:
                continue
            # prune_candidate = [cdd for cdd, prob in zip(candidate_prompt, candidate_probs) if prob>0.1]

