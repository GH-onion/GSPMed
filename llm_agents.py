# 模块1: Agent 1
# visual concept classification from modality-aligned models such as BioCLIP
def agent_caption(question: str, prompt_list: List[str], answer_list: Optional[List[str]]=None) -> List[str]:
    responses = []
    task = '''Now your are given a question and a hint, the hint is a caption describing the medical image. Your task: is to directly answer the question based on your thoughts and the given hint.
    '''
    for prompt in prompt_list:
        response = tot_agent.run(task, question, [prompt], prev_answer=answer_list)
        response = f"[Agent1] 回答: {response}"  # 示例返回
        responses.append(response)
    return responses


# 模块2: Agent 2
