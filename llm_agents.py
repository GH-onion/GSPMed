def load_prompts(json_path, image_name):
    with open(json_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    if image_name not in data:
        raise ValueError(f"{image_name} not found in prompt file.")
    return data[image_name]  # 返回该图像的 prompt 列表


def load_prompts_from_folder(folder_path):
    prompts_dict = {}
    for filename in os.listdir(folder_path):
        if filename.endswith('.json'):
            image_id = filename[:-5]  # 去掉 .json
            with open(os.path.join(folder_path, filename), 'r', encoding='utf-8') as f:
                prompts = json.load(f)
            prompts_dict[image_id] = prompts
    return prompts_dict


def load_candidate_prompts(candidate_json_path):
    with open(candidate_json_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    prompts_dict = {}
    for image_id, info in data.items():
        if "top_10_preds" in info:
            prompts_dict[image_id] = info["top_10_preds"]
    return prompts_dict


def load_captions_prompts(captions_json_path):
    with open(captions_json_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    prompts_dict = {}
    for image_id, info in data.items():
        if "caption" in info:
            # 统一为列表格式，便于后续处理
            prompts_dict[image_id] = [info["caption"]]
    return prompts_dict


def find_imageid_in_jsons(folder_path, image_id, field):
    # 遍历文件夹下所有json，找到包含image_id的，返回指定字段内容
    for filename in os.listdir(folder_path):
        if filename.endswith('.json'):
            with open(os.path.join(folder_path, filename), 'r', encoding='utf-8') as f:
                data = json.load(f)
            if image_id in data and field in data[image_id]:
                value = data[image_id][field]
                # 统一为列表格式
                return [value] if isinstance(value, str) else value
    return None


def find_imageid_in_json(file_path, image_id, field):
    # 遍历文件夹下所有json，找到包含image_id的，返回指定字段内容
    with open(file_path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    if image_id in data and field in data[image_id]:
        value = data[image_id][field]
        # 统一为列表格式
        return [value] if isinstance(value, str) else value
    return None


def append_to_json(results_dict: Dict[str, Any], json_path: str):
    '''
    Save current results into target json file (appending in case coverring formal results)

    arrtibutes:
        results_dict: current results
        json_path: target json path
    '''
    path = Path(json_path)
    if path.exists():
        existing = json.loads(path.read_text())
    else:
        existing = {}
    
    for k, v in results_dict.items():
        existing[k] = v

    path.write_text(json.dumps(existing, indent=2, ensure_ascii=False))


def check_json(image_id: str, json_path: str) -> bool:
    '''
    Check if the current image is already answered

    attributes:
        image_id: current image id
        json_path: the json path to look for
    '''
    path =Path(json_path)
    if not path.exists():
        # json not created, create it first
        path.parent.mkdir(parents=True, exist_ok=True)  # 确保上级目录存在
        path.write_text(json.dumps({}), encoding="utf-8")
        return False
    
    with path.open('r', encoding='utf-8') as f:
        data = json.load(f)
        if image_id in data.keys():
             return True
        
    return False


